"""Read-only verification; evidence integrity never upgrades a failed policy."""
import argparse
import csv
import json
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation

from .go2_kinematics import Go2Kinematics
from .rolling_native_audit import (_surface, _verify_calibration,
                                   verify_finite_rows, verify_world_ticks)
from .rolling_approved_source import verify_heightfield
from .video_materials import inspect_video, sha
from .evaluation_status import substep_events


def verify_time_grid(times, dt, terminal):
    times = np.asarray(times, dtype=float)
    expected = np.arange(round(terminal / dt) + 1) * dt
    if (times.shape != expected.shape or not np.isfinite(times).all()
            or not np.allclose(times, expected, rtol=0, atol=1e-8)):
        raise ValueError('Missing/duplicate/nonfinite/off-grid evidence samples')
    return len(times)


def audit(run):
    run = Path(run)
    result = json.loads((run / 'result.json').read_text())
    if result['status'] in ('ERROR', 'TIMEOUT', 'initializing'):
        raise ValueError('Evaluation did not complete: ' + result['status'])
    checkpoint = Path(result['args']['checkpoint'])
    if sha(checkpoint) != result['checkpoint_sha256']:
        raise ValueError('Evaluated checkpoint changed')
    for key in ('actor_unchanged', 'optimizer_unchanged', 'checkpoint_file_unchanged'):
        if result.get(key) is not True:
            raise ValueError('Inference mutated state: ' + key)
    for name, digest in result['source_sha256s'].items():
        if sha(run / 'source' / name) != digest:
            raise ValueError('Frozen source changed: ' + name)
    states = list(csv.DictReader((run / 'states.csv').open()))
    controls = list(csv.DictReader((run / 'controls.csv').open()))
    verify_finite_rows(states)
    verify_finite_rows(controls)
    safety = substep_events(states)
    if result.get('numeric_pass') is True and safety['unsafe']:
        raise ValueError('Numeric PASS contains a recorded unsafe substep')
    terminal = result['terminal_sim_s']
    verify_time_grid([float(r['time_s']) for r in states], .01, terminal)
    verify_time_grid([float(r['time_s']) for r in controls], .02, terminal)
    if len(states) != result['rows'] or len(controls) != result['control_samples']:
        raise ValueError('Sample counts differ from result')
    # save_audit uses a portable grid independent of the optional media recorder.
    source = verify_heightfield(Path(__file__).resolve().parents[2]
                                / 'assets/approved/heightfield.npz')
    kind = result['evaluation_kind']
    if kind == 'FLAT':
        height = np.zeros_like(source['height_m'])
        if result.get('approved_source') is not False:
            raise ValueError('Plane cannot claim to be the approved rolling Terrain')
    elif kind == 'ROLLING_UNEVEN':
        height = source['height_m']
        if result.get('approved_source') is not True:
            raise ValueError('Approved rolling identity missing')
    else:
        # The exact heldout grid must be frozen, not regenerated by the auditor.
        with np.load(run / 'terrain-source-and-quantized.npz') as data:
            height = data['height_m']
    x, y = source['x'], source['y']
    base = np.array([[float(r[k]) for k in ('x_m', 'y_m', 'height_m')] for r in states])
    quats = np.array([json.loads(r['quaternion_wxyz']) for r in states])
    rotations = Rotation.from_quat(quats[:, [1, 2, 3, 0]])
    kin = Go2Kinematics()
    if sha(kin.urdf_path) != result['physical_build']['robot_urdf_sha256']:
        raise ValueError('URDF identity changed')
    support_errors, fk_errors = {}, {}
    for leg in ('FL', 'FR', 'RL', 'RR'):
        centers = np.array([[float(r[f'{leg}_center_{a}_m']) for a in 'xyz'] for r in states])
        q = np.array([[float(r[f'{leg}_{j}_joint_position_rad'])
                       for j in ('hip', 'thigh', 'calf')] for r in states])
        fk_errors[leg] = float(np.linalg.norm(rotations.apply(kin.fk(leg, q)) + base - centers, axis=1).max())
        supports = np.array([float(r[f'{leg}_terrain_height_m']) for r in states])
        wanted = _surface(x, y, height, centers[:, :2])
        support_errors[leg] = float(abs(supports - wanted).max())
        if fk_errors[leg] >= 1e-4 or support_errors[leg] >= 1e-5:
            raise ValueError('FK/native support verification failed: ' + leg)
    contacts = [json.loads(line) for line in (run / 'contacts.jsonl').read_text().splitlines()]
    positive = 0
    for event in contacts:
        p = np.asarray(event['position_m'])
        f = np.asarray(event['force_on_robot_N'])
        if not np.isfinite(np.r_[p, f, event['penetration_m']]).all():
            raise ValueError('Nonfinite contact')
        wanted = float(_surface(x, y, height, p[None, :2])[0])
        if abs(wanted - event['native_support_z_m']) >= 1e-5:
            raise ValueError('Contact support mismatch')
        loaded = bool(np.linalg.norm(f) > 1e-6)
        if loaded != event['positive_force']:
            raise ValueError('Contact force flag mismatch')
        positive += int(loaded and event['foot'])
    if positive != result['actual_positive_foot_terrain_contacts']:
        raise ValueError('Contact counts mismatch')
    media = {}
    if result['recording_performed']:
        directory = run / 'native-media'
        metadata = json.loads((directory / 'recording-metadata.json').read_text())
        for name, key in (('terrain-input.npz', 'terrain_input_sha256'),
                          ('viridis-lut.npy', 'viridis_lut_sha256'),
                          ('source/rolling_uneven_media.py', 'source_sha256')):
            if sha(directory / name) != metadata[key]:
                raise ValueError('Frozen recording artifact changed: ' + name)
        if metadata['pose_replay'] or metadata['interpolated_poses'] or metadata['new_physics_steps_by_recorder']:
            raise ValueError('Recording is not direct native capture')
        with np.load(directory / 'terrain-input.npz') as recorded:
            np.testing.assert_allclose(recorded['height_m'], height, rtol=0, atol=1e-12)
        frames = [json.loads(line) for line in (directory / 'camera-frame-map.jsonl').read_text().splitlines()]
        frame_map = list(csv.DictReader((directory / 'frame-map.csv').open()))
        counts = dict.fromkeys(('side', 'oblique', 'overhead'), 0)
        indexed = {round(float(r['time_s']), 8): r for r in states}
        for frame, mapped in zip(frames, frame_map, strict=True):
            view = frame['view']
            if mapped['view'] != view or int(mapped['frame']) != frame['frame']:
                raise ValueError('Raw-frame and calibration identities differ')
            if frame['frame'] != counts[view]:
                raise ValueError('Camera frame missing/duplicate')
            tm = frame['simulation_time_s']
            if abs(tm - counts[view] / 25) > 1e-8 or abs(frame['video_pts_s'] - tm) > 1e-8:
                raise ValueError('Camera and physics time mismatch')
            row = indexed[round(tm, 8)]
            np.testing.assert_allclose(frame['base_position_m'],
                                       [float(row[k]) for k in ('x_m', 'y_m', 'height_m')], atol=1e-6, rtol=0)
            _verify_calibration(frame)
            verify_world_ticks(frame)
            if (sha(mapped['raw_png']) != frame['raw_png_sha256']
                    or mapped['raw_png_sha256'] != frame['raw_png_sha256']):
                raise ValueError('Raw frame changed')
            counts[view] += 1
        expected_frames = int(terminal * 25 + 1e-6) + 1
        if set(counts.values()) != {expected_frames} or metadata['frames_per_view'] != expected_frames:
            raise ValueError('Video truncated before evaluation terminal')
        for view, count in counts.items():
            for suffix in ('', '-raw'):
                movie = directory / f'native-{view}{suffix}.mp4'
                info = inspect_video(movie, decode=True)
                if info['frames'] != count:
                    raise ValueError('Decoded frames differ from native camera frames')
                media[movie.name] = info
    report = {'evidence_status': 'PASS', 'model_status': result['status'],
              'numeric_gates': result['numeric_gates'], 'kind': kind,
              'checkpoint_sha256': result['checkpoint_sha256'],
              'state_rows': len(states), 'control_rows': len(controls),
              'FK_max_errors_m': fk_errors, 'support_max_errors_m': support_errors,
              'positive_foot_contacts': positive, 'movies_fully_decoded': media,
              'substep_safety': safety,
              'visual_gate_F': result['visual_gate_F'], 'policy_success_inferred_from_video_integrity': False}
    (run / 'evidence-audit.json').write_text(json.dumps(report, indent=2) + '\n')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('runs', nargs='+', type=Path)
    for run in parser.parse_args().runs:
        report = audit(run)
        print(run.name, report['evidence_status'], report['model_status'], flush=True)
